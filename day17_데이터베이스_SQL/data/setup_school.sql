DROP TABLE IF EXISTS enrol;
DROP TABLE IF EXISTS subject;
DROP TABLE IF EXISTS student;
DROP TABLE IF EXISTS department;
DROP TABLE IF EXISTS club;

CREATE TABLE department (
    dept_id   text PRIMARY KEY,
    dept_name text NOT NULL UNIQUE,
    building  text
) STRICT;

CREATE TABLE student (
    stu_no   text PRIMARY KEY,
    stu_name text NOT NULL,
    dept_id  text NOT NULL REFERENCES department(dept_id),
    grade    int  NOT NULL CHECK (grade BETWEEN 1 AND 4),
    class    text NOT NULL,
    gender   text NOT NULL CHECK (gender IN ('M', 'F')),
    height   real,
    weight   real
) STRICT;

CREATE TABLE subject (
    sub_no   text PRIMARY KEY,
    sub_name text NOT NULL,
    credit   int  NOT NULL,
    dept_id  text NOT NULL REFERENCES department(dept_id)
) STRICT;

CREATE TABLE enrol (
    sub_no    text NOT NULL REFERENCES subject(sub_no),
    stu_no    text NOT NULL REFERENCES student(stu_no),
    enr_grade int,
    PRIMARY KEY (sub_no, stu_no)
) STRICT;

